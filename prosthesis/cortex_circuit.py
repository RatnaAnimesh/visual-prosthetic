"""A V1 circuit layer for cortical prosthesis simulation.

The models the field currently uses treat an electrode as producing a Gaussian
blob at its retinotopic position, and treat electrodes as independent.  Phase 0
measured that independence and found it exact to 3.7e-9 -- it is built in, not
approximate.

This module adds the one thing those models leave out: the horizontal
connections of V1.

Superficial pyramidal cells send axons for millimetres parallel to the
cortical surface and terminate in *clusters on columns of similar orientation
preference* (Gilbert & Wiesel; Kandel Fig. 25-16).  An electrode does not only
depolarise the cells beneath it -- it recruits those passing axons, exactly as
a retinal electrode recruits the nerve fibre bundles passing over it.  That
retinal effect is what turned predicted phosphenes from round dots into
elongated comets and broke the pixel assumption.  The cortical analogue has
not been tested.

Because the horizontal kernel is *orientation selective*, the activation it
spreads is not isotropic: it follows the iso-orientation domains around the
electrode, which are patchy.  The prediction is therefore a phosphene with
internal structure rather than a clean Gaussian, and -- because two electrodes
can share iso-orientation domains -- an interaction between electrodes that no
independent model can express.

Design note: this is a *field* model, at the same level of abstraction as
Dynaphos, not a spiking one.  That is deliberate.  It keeps the comparison
like-for-like, it is fast enough to sweep, and it stays differentiable for the
encoder work later.  The spiking column model in ``column/`` is the ground
truth to check specific predictions against, not the thing to run inside a
parameter sweep.
"""

from __future__ import annotations

import numpy as np
from scipy.ndimage import gaussian_filter, map_coordinates

from pulse2percept.models.cortex.base import CortexSpatial

# --- Cortical constants ----------------------------------------------------
# Orientation columns cycle through 180 degrees roughly every 750 um in
# macaque V1 (Kandel Fig. 25-11C).  Long-range horizontal axons extend a few
# millimetres and prefer targets within ~25-30 degrees of their own
# orientation preference.
COLUMN_SPACING_UM = 750.0
HORIZ_SIGMA_UM = 1000.0
HORIZ_SIGMA_THETA_DEG = 27.0

# Dynaphos' current spread, reproduced exactly so that switching the circuit
# off recovers the baseline: activated tissue diameter D = 2*sqrt(I/K) mm.
EXCITABILITY_UA_PER_MM2 = 675.0


def orientation_map(shape, step_um, spacing_um=COLUMN_SPACING_UM,
                    seed=0) -> np.ndarray:
    """A realistic V1 orientation preference map, in degrees, modulo 180.

    Generated by band-pass filtering complex Gaussian noise and taking half
    its phase -- the standard construction (Rojer & Schwartz).  It reproduces
    the properties that matter here: quasi-periodic iso-orientation domains at
    the right spatial scale, joined at pinwheel singularities, without the
    artificial regularity of a single hand-placed pinwheel.
    """
    rng = np.random.default_rng(seed)
    ny, nx = shape
    z = rng.normal(size=shape) + 1j * rng.normal(size=shape)

    fy = np.fft.fftfreq(ny, d=step_um)[:, None]
    fx = np.fft.fftfreq(nx, d=step_um)[None, :]
    f = np.sqrt(fx ** 2 + fy ** 2)

    # Annular band-pass at the column spatial frequency.
    f0 = 1.0 / spacing_um
    bandwidth = 0.35 * f0
    filt = np.exp(-((f - f0) ** 2) / (2 * bandwidth ** 2))

    zf = np.fft.ifft2(np.fft.fft2(z) * filt)
    return (np.rad2deg(np.angle(zf)) / 2.0) % 180.0


class CircuitSpatial(CortexSpatial):
    """Cortical phosphene model with iso-orientation horizontal spread.

    Set ``horiz_gain=0`` to disable the circuit entirely, which reduces the
    model to the same Gaussian current spread Dynaphos uses.  That is the
    control condition, and it is what makes any difference attributable to the
    circuit rather than to a different current-spread model.

    Parameters
    ----------
    horiz_gain : float
        Strength of horizontal recruitment relative to direct activation.
        0 disables it.
    horiz_sigma : float
        Spatial extent of horizontal axons (microns).
    horiz_theta_sigma : float
        Orientation tuning width of horizontal connections (degrees).
    excitability : float
        Current spread constant (uA/mm^2); activated tissue diameter is
        2*sqrt(amp/excitability) mm.
    cortex_step : float
        Resolution of the internal cortical grid (microns).
    """

    def __init__(self, **params):
        super().__init__(**params)
        self._cgrid = None

    def get_default_params(self):
        base = super().get_default_params()
        return {**base, **{
            "horiz_gain": 0.6,
            "horiz_sigma": HORIZ_SIGMA_UM,
            "horiz_theta_sigma": HORIZ_SIGMA_THETA_DEG,
            "column_spacing": COLUMN_SPACING_UM,
            "excitability": EXCITABILITY_UA_PER_MM2,
            "cortex_step": 50.0,
            "cortex_margin": 4000.0,
            "map_seed": 0,
            # Divisive normalisation (Carandini & Heeger).  Off by default so
            # that the model reduces exactly to current spread and the
            # size-vs-current calibration stays valid.
            #
            # This is the part that can break electrode independence.  Linear
            # spread -- however elaborate, and however orientation-selective --
            # cannot: a linear operator applied to (A + B) is by definition
            # the sum of its application to A and to B.  Interaction requires
            # a nonlinearity, and divisive normalisation is the one V1 is
            # best documented to have.
            # Amplitude -> activation magnitude (see _activation_field).
            "amp_a50": 150.0,
            "amp_exponent": 2.0,
            "norm_gain": 0.0,
            "norm_sigma": 1500.0,   # pooling extent (microns)
            # A second, much broader suppressive pool.  V1 surround
            # suppression is not one mechanism but two: a near component with
            # the reach of horizontal connections, and a far component
            # mediated by feedback from extrastriate areas whose receptive
            # fields are several times larger.  At ~2 deg eccentricity an
            # MT-sized surround corresponds to on the order of a centimetre of
            # V1 cortex, far beyond anything horizontal axons can cover.
            #
            # Off by default: it exists to test whether long-range
            # phosphene suppression needs it, not as part of the baseline
            # claim.
            "norm_far_gain": 0.0,
            "norm_far_sigma": 6000.0,
            "norm_semi": 0.30,      # semi-saturation constant
            "expansive_n": 2.0,     # expansive exponent before pooling
            "ndim": [2, 3],
        }}

    # -- internal cortical sheet -------------------------------------------

    def _ensure_cortical_grid(self, x_el, y_el):
        """Lay a uniform cortical grid over the array, with margin for spread.

        The visual-field grid cannot be used for this: it samples cortex
        non-uniformly (densely at the fovea), and the circuit lives in cortex,
        uniformly.  Doing the convolutions on a uniform sheet avoids having to
        carry a Jacobian through them.
        """
        m = self.cortex_margin
        xs = np.arange(x_el.min() - m, x_el.max() + m, self.cortex_step)
        ys = np.arange(y_el.min() - m, y_el.max() + m, self.cortex_step)
        key = (xs[0], xs[-1], ys[0], ys[-1], len(xs), len(ys))
        if self._cgrid is not None and self._cgrid["key"] == key:
            return self._cgrid

        theta = orientation_map((len(ys), len(xs)), self.cortex_step,
                                self.column_spacing, seed=self.map_seed)
        self._cgrid = {
            "key": key, "xs": xs, "ys": ys, "theta": theta,
            "cos2t": np.cos(2 * np.deg2rad(theta)),
            "sin2t": np.sin(2 * np.deg2rad(theta)),
        }
        return self._cgrid

    def _horizontal_spread(self, direct, g):
        """Recruit iso-orientation horizontal axons.

        The kernel is separable in an unobvious way.  Writing the orientation
        similarity to first Fourier order,

            s(dtheta) ~ (1 + r cos 2*dtheta) / (1 + r)

        and expanding cos(2(t_i - t_j)), the orientation-weighted sum over
        cortex becomes *three* plain Gaussian blurs:

            G(A)  +  r cos2t_i * G(A cos2t)  +  r sin2t_i * G(A sin2t)

        all divided by (1 + r).  Three convolutions instead of an N^2 kernel,
        which is what makes a millimetre-scale sheet tractable -- and keeps the
        whole model differentiable for the encoder work later.
        """
        sigma_px = self.horiz_sigma / self.cortex_step
        # Map the orientation tuning width onto the first-harmonic weight r.
        # r -> 0 gives orientation-blind spread, r -> 1 maximally selective.
        st = np.deg2rad(self.horiz_theta_sigma)
        r = float(np.exp(-2.0 * st ** 2))

        blur = lambda a: gaussian_filter(a, sigma_px, mode="nearest")
        c, s = g["cos2t"], g["sin2t"]
        iso = blur(direct) + r * (c * blur(direct * c) + s * blur(direct * s))
        return iso / (1.0 + r)

    # -- the model ----------------------------------------------------------

    def _activation_field(self, amps, x_el, y_el, g):
        """Cortical activation for one set of electrode amplitudes."""
        X, Y = np.meshgrid(g["xs"], g["ys"])
        direct = np.zeros(X.shape)

        for a, xe, ye in zip(amps, x_el, y_el):
            a = abs(float(a))
            if a <= 0:
                continue
            # Dynaphos: activated tissue diameter D = 2*sqrt(I/K) mm.
            sigma_um = 1000.0 * np.sqrt(a / self.excitability)
            if sigma_um <= 0:
                continue
            # Amplitude also sets how hard the tissue is driven, not only how
            # much of it is recruited.  Without this an electrode's activation
            # peaks at 1 whatever the current, so amplitude controls phosphene
            # size but not brightness -- which leaves an encoder no graded
            # control to optimise.  Scaling the whole Gaussian by a saturating
            # function of current leaves the half-maximum contour untouched,
            # so the Phase 1 size-vs-current calibration still holds.
            n = self.amp_exponent
            height = a ** n / (a ** n + self.amp_a50 ** n)
            d2 = (X - xe) ** 2 + (Y - ye) ** 2
            direct += height * np.exp(-d2 / (2 * sigma_um ** 2))

        if not direct.any():
            return direct

        total = direct
        if self.horiz_gain > 0:
            total = direct + self.horiz_gain * self._horizontal_spread(direct, g)

        if self.norm_gain <= 0 and self.norm_far_gain <= 0:
            return total

        # Divisive normalisation: each site's response is divided by a pooled
        # measure of activity in its neighbourhood.  Two electrodes that share
        # a pool suppress each other, which is what makes the response to both
        # less than the sum of the responses to each.
        n = self.expansive_n
        num = np.power(total, n)
        pool = 0.0
        if self.norm_gain > 0:
            pool = self.norm_gain * gaussian_filter(
                num, self.norm_sigma / self.cortex_step, mode="nearest")
        if self.norm_far_gain > 0:
            pool = pool + self.norm_far_gain * gaussian_filter(
                num, self.norm_far_sigma / self.cortex_step, mode="nearest")
        return num / (self.norm_semi ** n + pool)

    def _sample_to_visual_field(self, field, g, region):
        """Read the cortical field out at each visual-field grid point."""
        gx = np.asarray(self.grid[region].x).ravel()
        gy = np.asarray(self.grid[region].y).ravel()
        col = (gx - g["xs"][0]) / self.cortex_step
        row = (gy - g["ys"][0]) / self.cortex_step
        inside = ((col >= 0) & (col <= len(g["xs"]) - 1) &
                  (row >= 0) & (row <= len(g["ys"]) - 1))
        out = np.zeros(gx.size)
        if inside.any():
            out[inside] = map_coordinates(
                field, [row[inside], col[inside]], order=1, mode="constant"
            )
        return out

    def _predict_spatial(self, earray, stim):
        x_el = np.array([earray[e].x for e in stim.electrodes], dtype=float)
        y_el = np.array([earray[e].y for e in stim.electrodes], dtype=float)
        g = self._ensure_cortical_grid(x_el, y_el)

        data = np.asarray(stim.data, dtype=float)  # (n_electrodes, n_time)
        n_time = data.shape[1]

        # A pulse train visits only a handful of distinct amplitude vectors,
        # so solve each once and index back rather than recomputing per frame.
        rounded = np.round(np.abs(data), 6)
        uniq, inverse = np.unique(rounded, axis=1, return_inverse=True)

        n_pts = sum(np.asarray(self.grid[r].x).size for r in self.regions)
        cache = np.zeros((n_pts, uniq.shape[1]))
        for k in range(uniq.shape[1]):
            if not uniq[:, k].any():
                continue
            field = self._activation_field(uniq[:, k], x_el, y_el, g)
            cache[:, k] = np.concatenate(
                [self._sample_to_visual_field(field, g, r) for r in self.regions]
            )

        resp = cache[:, inverse]
        peak = resp.max()
        if peak > 0:
            resp = resp / peak
        resp[resp < self.thresh_percept] = 0
        return resp.reshape(n_pts, n_time).astype(np.float32)
